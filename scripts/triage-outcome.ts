// The Triage workflow's outcome check: fails the run unless the agent left one category label,
// one outcome label and a new triage reasons comment, then sets the board Status to match
// (Ready for `ready` unless someone has claimed it, HITL for the rest). A failed check sets
// nothing. Needs the same token as board-status.
//
//   bun run triage-outcome <issue-number> <since-comment-id>     e.g. bun run triage-outcome 25 0
//
// <since-comment-id> is the id of the issue's newest comment before the agent ran, 0 if none.

import { gh, moveToColumn, OWNER, REPO } from './board-status.ts'

export const USAGE = 'Usage: bun run triage-outcome <issue-number> <since-comment-id>  (e.g. 25 0)'

export function parseArgs(args: string[]): { issue: number; since: number } {
  const [issue = '', since = '', ...rest] = args
  if (!/^[1-9]\d*$/.test(issue) || !/^(0|[1-9]\d*)$/.test(since) || rest.length > 0) throw new Error(USAGE)
  return { issue: Number(issue), since: Number(since) }
}

export type Comment = { id: number; author: string; body: string }

export type OutcomeCheck = { pass: true; outcome: string } | { pass: false; reason: string }

// The line .github/prompts/triage.md tells the agent to start every comment with.
export const DISCLAIMER = '> *This was generated by AI during triage.*'

const CATEGORIES = ['bug', 'enhancement', 'documentation']
const OUTCOMES = ['ready', 'needs-info', 'ready-for-human', 'wontfix', 'needs-triage']

// A triage reasons comment: it starts with the disclaimer, and isn't the `Original note:` copy
// a `ready` triage posts before promoting the spec. Every triage posts one, whatever the outcome.
function isReasons(body: string): boolean {
  if (!body.startsWith(DISCLAIMER)) return false
  return !body.slice(DISCLAIMER.length).trimStart().startsWith('Original note:')
}

// Did this run triage the issue? Labels from an earlier triage satisfy the label rule on a
// re-run, so the run must also have posted a reasons comment newer than `since`, the id of the
// issue's newest comment before the agent started (0 if it had none).
export function checkOutcome(input: {
  labels: string[]
  comments: Comment[]
  since: number
  owner: string
}): OutcomeCheck {
  const { labels, comments, since, owner } = input
  const categories = labels.filter((label) => CATEGORIES.includes(label))
  const outcomes = labels.filter((label) => OUTCOMES.includes(label))
  const [outcome] = outcomes
  if (categories.length !== 1 || outcomes.length !== 1 || outcome === 'needs-triage') {
    return { pass: false, reason: `needs one category and one outcome label, has: ${labels.join(' ') || 'none'}` }
  }
  const fresh = comments.filter((comment) => comment.id > since)
  if (!fresh.some((comment) => comment.author === owner && isReasons(comment.body))) {
    const found =
      fresh.length === 0
        ? 'no new comments'
        : `${fresh.length} new comment${fresh.length === 1 ? '' : 's'}, none a triage reasons comment`
    return { pass: false, reason: `no new triage comment since comment ${since}: ${found}` }
  }
  return { pass: true, outcome }
}

function readIssue(issue: number): { labels: string[]; claimed: boolean; comments: Comment[] } {
  const { labels, assignees } = JSON.parse(
    gh(['issue', 'view', String(issue), '--repo', REPO, '--json', 'labels,assignees']),
  ) as { labels: { name: string }[]; assignees: unknown[] }
  // REST, not `gh issue view`: its comment ids are numeric and rise over time, like the marker.
  // One JSON object per line, across every page.
  const lines = gh([
    'api', '--paginate', `repos/${REPO}/issues/${issue}/comments?per_page=100`,
    '--jq', '.[] | {id, author: .user.login, body}',
  ])
  const comments = lines === '' ? [] : lines.split('\n').map((line) => JSON.parse(line) as Comment)
  return { labels: labels.map((label) => label.name), claimed: assignees.length > 0, comments }
}

if (import.meta.main) {
  try {
    const { issue, since } = parseArgs(process.argv.slice(2))
    const { labels, claimed, comments } = readIssue(issue)
    const result = checkOutcome({ labels, comments, since, owner: OWNER })
    if (!result.pass) {
      // A bad triage shows up as a red run, not a mislabelled issue.
      console.log(`::error::#${issue} ${result.reason}`)
      process.exit(1)
    }
    console.log(`#${issue} triaged: ${result.outcome}`)
    // Implement may already have claimed it and moved it to In progress.
    if (result.outcome === 'ready' && claimed) console.log(`#${issue} is claimed, Status left as it is`)
    else console.log(`#${issue} → ${moveToColumn(issue, result.outcome === 'ready' ? 'Ready' : 'HITL')}`)
  } catch (error) {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  }
}
