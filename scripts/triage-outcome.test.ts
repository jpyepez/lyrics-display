import { describe, expect, test } from 'vitest'
import { checkOutcome, parseArgs, USAGE } from './triage-outcome.ts'

const DISCLAIMER = '> *This was generated by AI during triage.*'
const owner = 'jpyepez'

// An issue triaged once before: its labels and its reasons comment (id 100) are already there.
const earlier = { id: 100, author: owner, body: `${DISCLAIMER}\n\nOutcome: \`needs-info\`.` }

describe('checkOutcome', () => {
  test('fails a re-triage that left the earlier labels but posted no new comment', () => {
    expect(
      checkOutcome({ labels: ['enhancement', 'needs-info'], comments: [earlier], since: 100, owner }),
    ).toEqual({ pass: false, reason: 'no new triage comment since comment 100' })
  })

  test('passes a run that posted a new triage comment and left one category and one outcome', () => {
    const fresh = { id: 140, author: owner, body: `${DISCLAIMER}\n\nOutcome: \`ready-for-human\`.` }
    expect(
      checkOutcome({ labels: ['bug', 'ready-for-human'], comments: [earlier, fresh], since: 100, owner }),
    ).toEqual({ pass: true, outcome: 'ready-for-human' })
  })

  test('passes a re-triage that came to the same outcome as last time', () => {
    const again = { id: 140, author: owner, body: `${DISCLAIMER}\n\nOutcome: \`needs-info\`, again.` }
    expect(
      checkOutcome({ labels: ['enhancement', 'needs-info'], comments: [earlier, again], since: 100, owner }),
    ).toEqual({ pass: true, outcome: 'needs-info' })
  })

  test('passes a new issue that had no comments before the run (marker 0)', () => {
    const first = { id: 7, author: owner, body: `${DISCLAIMER}\n\nOutcome: \`wontfix\`.` }
    expect(checkOutcome({ labels: ['enhancement', 'wontfix'], comments: [first], since: 0, owner })).toEqual({
      pass: true,
      outcome: 'wontfix',
    })
  })

  test("doesn't count a new comment the owner typed without the disclaimer", () => {
    const typed = { id: 140, author: owner, body: 'Re-running triage on this one.' }
    expect(
      checkOutcome({ labels: ['enhancement', 'needs-info'], comments: [earlier, typed], since: 100, owner }),
    ).toEqual({ pass: false, reason: 'no new triage comment since comment 100' })
  })

  test("doesn't count a disclaimer comment someone other than the owner posted", () => {
    const copied = { id: 140, author: 'someone-else', body: `${DISCLAIMER}\n\nOutcome: \`ready\`.` }
    expect(
      checkOutcome({ labels: ['enhancement', 'needs-info'], comments: [earlier, copied], since: 100, owner }),
    ).toEqual({ pass: false, reason: 'no new triage comment since comment 100' })
  })

  test("fails a ready triage that promoted the spec but didn't post its reasons", () => {
    const note = { id: 140, author: owner, body: `${DISCLAIMER}\n\nOriginal note:\n\nShow a wait state on 503.` }
    expect(
      checkOutcome({ labels: ['bug', 'ready'], comments: [earlier, note], since: 100, owner }),
    ).toEqual({ pass: false, reason: 'no new triage comment since comment 100' })
  })

  test.each([
    [['bug', 'enhancement', 'needs-info'], 'bug enhancement needs-info'],
    [['bug', 'needs-info', 'ready'], 'bug needs-info ready'],
    [['bug', 'needs-triage'], 'bug needs-triage'],
    [['needs-info'], 'needs-info'],
    [[], 'none'],
  ])('fails labels %j even with a new triage comment', (labels, has) => {
    const fresh = { id: 140, author: owner, body: `${DISCLAIMER}\n\nOutcome: \`needs-info\`.` }
    expect(checkOutcome({ labels, comments: [earlier, fresh], since: 100, owner })).toEqual({
      pass: false,
      reason: `needs one category and one outcome label, has: ${has}`,
    })
  })
})

describe('parseArgs', () => {
  test('reads the issue number and the marker, which is 0 for an issue with no comments', () => {
    expect(parseArgs(['25', '3456789012'])).toEqual({ issue: 25, since: 3456789012 })
    expect(parseArgs(['25', '0'])).toEqual({ issue: 25, since: 0 })
  })

  test.each([[[]], [['25']], [['abc', '0']], [['0', '0']], [['25', '-1']], [['25', 'null']], [['25', '1', '2']]])(
    'rejects %j with the usage message',
    (args) => {
      expect(() => parseArgs(args)).toThrow(USAGE)
    },
  )
})
